# Pass-2 selection: five compounds per article (0-based indices)
pool = []
for order, suffix, n in INCLUDED:
    doi = "10.1021/acs.orglett." + suffix
    picks = sorted(random.Random(f"{STUDY_SEED}:{doi}").sample(range(n), min(5, n)))
    for idx in picks:
        pool.append((order, doi, idx))
print("Pool size:", len(pool))

# Blind-test selection (draw order kept: the first 20 drawn are set A)
draw = random.Random(BLIND_SEED).sample(range(len(pool)), N_BLIND)
sets = {"A": sorted(draw[:N_SET_A]), "B": sorted(draw[N_SET_A:])}
for name, positions in sets.items():
    print(f"\nSet {name}: {len(positions)} descriptions "
          "(pool position, order, DOI, compound index):")
    for p in positions:
        order, doi, idx = pool[p]
        print(f"{p:4d} Order {order:3d} {doi} index{idx}")
